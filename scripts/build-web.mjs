// Turns web/mouawa.html (the full Mouawa page built for the app) into a JS module the app bundles.
// Run after replacing web/mouawa.html:  npm run build:web
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'web/mouawa.html'), 'utf8');
if (!html.includes('<head>')) throw new Error('web/mouawa.html must contain a <head> tag');
const out = `// Generated by scripts/build-web.mjs from web/mouawa.html. Do not edit by hand.\n/* eslint-disable */\nexport default ${JSON.stringify(html)};\n`;
writeFileSync(join(root, 'src/mouawaHtml.js'), out);
console.log(`src/mouawaHtml.js written (${(out.length / 1024).toFixed(0)} KB)`);
